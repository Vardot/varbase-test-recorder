/**
 * Check if a field is required by its label name.
 */
async function checkFieldIsRequiredByName(page, fieldName) {
  const label = page.locator('label, span').filter({ hasText: fieldName }).first();
  await label.scrollIntoViewIfNeeded();
  await expect(label).toBeVisible();
  const isRequired = await label.evaluate((el) => {
    return el.classList.contains('js-form-required') ||
      el.classList.contains('form-required') ||
      el.classList.contains('required') ||
      el.textContent.includes('*') ||
      el.querySelector('.form-required') !== null;
  });
  const forId = await label.getAttribute('for');
  let inputRequired = false;
  if (forId) {
    inputRequired = await page.locator('#' + forId).evaluate(
      (el) => el.required || el.getAttribute('required') !== null
    ).catch(() => false);
  }
  expect(isRequired || inputRequired).toBeTruthy();
}

