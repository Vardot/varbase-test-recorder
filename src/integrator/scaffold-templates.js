/**
 * Check for a Drupal status message and capture the URL.
 */
async function checkStatusMessage(page, type, capturedUrls = {}) {
  const messageEl = page.locator('.messages--status, .messages, .alert, .messages__content').first();
  const patterns = {
    created: /has been created|has been saved/i,
    updated: /has been updated/i,
    deleted: /has been deleted/i,
    cloned: /clone.*has been created|has been cloned|node was cloned/i,
    saved: /has been saved/i,
  };
  await expect(messageEl).toContainText(patterns[type] || patterns.created, { timeout: 10000 });
  if (['created', 'updated', 'saved'].includes(type)) {
    capturedUrls.lastPageUrlforsaved = page.url();
  } else if (type === 'cloned') {
    capturedUrls.lastPageUrlforCloned = page.url();
  }
}

